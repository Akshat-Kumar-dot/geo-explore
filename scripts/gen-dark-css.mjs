/**
 * Generates src/styles/dark-overrides.css: a dark-mode rule for every hard-coded
 * colour utility in src (bg-[#…], text-[#…], border-[#…], bg-white/95, …).
 * Tailwind tokens are themed through CSS variables instead; this covers the rest.
 *
 * Blue-grey neutrals become true neutral greys around the #191919 base, so the
 * dark theme is charcoal rather than navy. Saturated colours keep their hue.
 *
 * Run after adding new hard-coded colour classes: node scripts/gen-dark-css.mjs
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = new URL('../src/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const OUT = join(SRC, 'styles', 'dark-overrides.css');

const files = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? files(p) : /\.(tsx?|css)$/.test(f) ? [p] : [];
});

const RE = /(?<![\w-])((?:hover|focus|group-hover|placeholder|disabled):)?(bg|text|border|ring|divide)-(\[#([0-9a-fA-F]{6})\]|white|black)(?:\/(\d{1,3}))?(?![\w\]-])/g;

const hexToHsl = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l, 0];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l, d];
};
const clamp = (x, a, b) => Math.min(b, Math.max(a, x));
const hsl = (h, s, l, a) => `hsl(${h.toFixed(0)} ${(s * 100).toFixed(0)}% ${(clamp(l, 0, 1) * 100).toFixed(1)}%${a != null ? ` / ${a}` : ''})`;

/** Dark equivalent for one colour in one role. Returns null to leave it alone. */
function darken(prop, hex) {
  const [h, s, l, chroma] = hexToHsl(hex);
  // Chroma, not HSL saturation: pale blue-greys have high saturation but almost no colour.
  const neutral = chroma < 0.17;
  if (prop === 'text') {
    if (l > 0.9) return null;                                 // white text stays white
    if (neutral) return hsl(0, 0, 0.93 - l * 0.62);           // ink → near-white, greys → mid greys
    return l < 0.55 ? hsl(h, Math.min(s, 0.6), 0.7) : null;   // status text: lift for contrast
  }
  if (prop === 'bg') {
    if (neutral) return l > 0.5 ? hsl(0, 0, clamp(0.13 + (1 - l) * 1.5, 0.13, 0.36)) : hsl(0, 0, 0.2 + l * 0.5);
    return l > 0.85 ? hsl(h, 0.3, 0.17) : null;               // pale status tints → dark tints
  }
  // border, ring, divide
  if (neutral) return hsl(0, 0, clamp(0.18 + (1 - l) * 0.5, 0.18, 0.34));
  return l > 0.75 ? hsl(h, 0.25, 0.3) : null;
}

const esc = (cls) => cls.replace(/[[\]#/:.]/g, (c) => `\\${c}`);
const CSS_PROP = { bg: 'background-color', text: 'color', border: 'border-color', ring: '--tw-ring-color', divide: 'border-color' };

const seen = new Map();
for (const f of files(SRC)) {
  if (f.endsWith('dark-overrides.css')) continue;
  for (const m of readFileSync(f, 'utf8').matchAll(RE)) seen.set(m[0], m);
}

const rules = [];
for (const [cls, m] of [...seen].sort(([a], [b]) => a.localeCompare(b))) {
  const [, variant, prop, , hex, alpha] = m;
  const base = m[3] === 'white' ? 'ffffff' : m[3] === 'black' ? '000000' : hex;
  if (m[3] === 'black') continue;
  const value = darken(prop, base);
  if (!value) continue;
  const a = alpha != null ? Number(alpha) / 100 : null;
  const v = a != null ? value.replace(/\)$/, ` / ${a})`) : value;
  const pseudo = variant === 'hover:' ? ':hover' : variant === 'focus:' ? ':focus' : variant === 'disabled:' ? ':disabled' : '';
  let sel = `html.dark .${esc(cls)}${pseudo}`;
  if (variant === 'group-hover:') sel = `html.dark .group:hover .${esc(cls)}`;
  if (variant === 'placeholder:') sel = `html.dark .${esc(cls)}::placeholder`;
  const decl = prop === 'divide' ? `${CSS_PROP[prop]}: ${v}` : `${CSS_PROP[prop]}: ${v}`;
  rules.push(prop === 'divide'
    ? `html.dark .${esc(cls)} > :not([hidden]) ~ :not([hidden]) { ${decl}; }`
    : `${sel} { ${decl}; }`);
}

writeFileSync(OUT, `/* GENERATED by scripts/gen-dark-css.mjs — do not edit by hand. */\n${rules.join('\n')}\n`);
console.log(`Wrote ${rules.length} dark rules for ${seen.size} colour classes to ${OUT}`);
